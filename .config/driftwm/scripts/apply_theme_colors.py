# ----------------------------------------------------- targeted patches ----
def patch(path, pattern, replacement, count=0):
    p = Path(path)
    text = p.read_text()
    new_text, n = re.subn(pattern, replacement, text, count=count, flags=re.M)
    if n:
        p.write_text(new_text)


def driftwm_config(t):
    p = CFG / "driftwm/config.toml"
    patch(p, r'^bg_color = ".*"$', f'bg_color = "{t["BG"]}"')
    patch(p, r'^fg_color = ".*"$', f'fg_color = "{t["FG"]}"')
    # The idle-lock swayidle line spawns swaylock with its own hardcoded
    # (no "#") hex args, separate from swaylock/config's own colors above.
    hx = lambda k: t[k].lstrip("#")
    patch(p, r"(swaylock -c )[0-9a-fA-F]{6}", rf'\g<1>{hx("BG")}')
    patch(p, r"(--inside-color )[0-9a-fA-F]{6}", rf'\g<1>{hx("TRACK")}')
    patch(p, r"(--ring-color )[0-9a-fA-F]{6}", rf'\g<1>{hx("BORDER")}')
    patch(p, r"(--text-color )[0-9a-fA-F]{6}", rf'\g<1>{hx("FG")}')
    patch(p, r"(--key-hl-color )[0-9a-fA-F]{6}", rf'\g<1>{hx("ACCENT")}')


def quickshell_theme(t):
    p = CFG / "driftwm/quickshell/Theme.qml"
    for prop, key in (("bg", "BG"), ("border", "BORDER"), ("fg", "FG"),
                       ("track", "TRACK"), ("accent", "ACCENT"), ("warm", "WARM")):
        patch(p, rf'(readonly property color {prop}: )"#[0-9a-fA-F]{{6,8}}"', rf'\1"{t[key]}"')


def zshrc(t):
    p = HOME / ".zshrc"
    rgb = lambda hexcolor: ";".join(str(int(hexcolor.lstrip("#")[i:i + 2], 16)) for i in (0, 2, 4))
    patch(p, r'(di=38;2;)[0-9;]+(?=:)', rf'\g<1>{rgb(t["ACCENT"])}')
    patch(p, r'(bd=38;2;)[0-9;]+(?=:)', rf'\g<1>{rgb(t["BORDER"])}')
    patch(p, r'(cd=38;2;)[0-9;]+(?=:)', rf'\g<1>{rgb(t["BORDER"])}')


def fuzzel(t):
    p = CFG / "fuzzel/fuzzel.ini"
    hx = lambda k: t[k].lstrip("#")
    for key, val in (
        ("background", hx("BG") + "ee"), ("text", hx("FG") + "ff"),
        ("prompt", hx("ACCENT") + "ff"), ("placeholder", hx("BORDER") + "ff"),
        ("input", hx("FG") + "ff"), ("message", hx("BORDER") + "ff"),
        ("match", hx("ACCENT") + "ff"), ("selection", hx("TRACK") + "ff"),
        ("selection-text", hx("WARM") + "ff"), ("selection-match", hx("CYAN") + "ff"),
        ("counter", hx("BORDER") + "ff"), ("border", hx("BORDER") + "ff"),
    ):
        patch(p, rf'^{key}=[0-9a-fA-F]+$', f'{key}={val}')


def reload_apps():
    for cmd in (
        ["pkill", "-SIGUSR2", "waybar"],
        ["swaync-client", "--reload-css"],
        ["driftwm", "msg", "action", "reload-config"],
    ):
        subprocess.run(cmd, capture_output=True)


def main():
    wallpaper_rel = sys.argv[1] if len(sys.argv) > 1 else "dark_sea.glsl"
    t = get_tokens(wallpaper_rel)

    kitty(t); ghostty(t); waybar(t); swaync(t); gtk(t)
    btop(t); cava(t); swaylock(t); zed(t); p10k(t)
    driftwm_config(t); quickshell_theme(t); zshrc(t); fuzzel(t)

    reload_apps()


if __name__ == "__main__":
    main()
