#!/usr/bin/env python3
"""Recolors the system to match the active wallpaper.

Run as: apply_theme_colors.py <wallpaper-relative-path, e.g. dark_sea.glsl>

Pipeline: render a wallpaper thumbnail already exists at
~/.config/driftwm/wallpapers/thumbs/ (gen_wallpaper_thumbs.sh) -> matugen
extracts a Material You palette from it -> we map a handful of matugen's
roles onto the small token set every themed file actually uses -> each
themed file is either rewritten whole (files that are 100% theme, nothing
else) or patched at specific known lines (files that mix theme with
unrelated settings, e.g. driftwm/config.toml or .zshrc).

Token contract (see also quickshell/Theme.qml, which carries the same six
color tokens for QML widgets):
    BG        background
    FG        text on BG
    BORDER    subtle borders/dividers
    TRACK     slightly-raised surface (selection bg, secondary panels)
    DARK      slightly-recessed surface (darker than BG)
    ACCENT    the one "brand" highlight color (active border, links, sliders)
    ON_ACCENT text drawn on top of an ACCENT-colored surface
    WARM      a second, distinct highlight (track titles, foam highlights)

Red/green/yellow/magenta/cyan (errors/warnings/git-status/ANSI colors) stay
FIXED across wallpapers on purpose — they carry meaning (error = red) that
shouldn't drift with the wallpaper, and Material You's role set doesn't
provide six independent hues to derive them from anyway.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
CFG = HOME / ".config"

FIXED = {
    "RED": "#b5665f", "RED_BR": "#c77a72",
    "GREEN": "#8a9a7c", "GREEN_BR": "#9dad8f",
    "YELLOW": "#c9b98a", "YELLOW_BR": "#dcccA0",
    "MAGENTA": "#9a8aa0", "MAGENTA_BR": "#ac9cb3",
    "CYAN": "#7fa6a0", "CYAN_BR": "#93bab4",
    "DIM": "#8f8a72", "PLACEHOLDER": "#6a6a5e",
}


def darken(hexcolor, factor):
    h = hexcolor.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return "#{:02x}{:02x}{:02x}".format(*(max(0, int(v * factor)) for v in (r, g, b)))


IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp", ".bmp"}


def thumb_for(wallpaper_rel):
    # A custom wallpaper picked via AppearanceSection's file dialog is
    # already a real photo — no shader thumbnail to render, use it as-is.
    direct = Path(wallpaper_rel).expanduser()
    if direct.is_absolute() and direct.suffix.lower() in IMAGE_SUFFIXES and direct.exists():
        return direct
    name = wallpaper_rel.replace("/", "_").replace(".glsl", ".png")
    p = CFG / "driftwm/wallpapers/thumbs" / name
    return p if p.exists() else CFG / "driftwm/wallpapers/thumbs/dark_sea.png"


def get_tokens(wallpaper_rel):
    thumb = thumb_for(wallpaper_rel)
    out = subprocess.run(
        ["matugen", "image", str(thumb), "--json", "hex", "--dry-run",
         "--mode", "dark", "--prefer", "darkness", "--lightness-dark", "0.15"],
        capture_output=True, text=True, check=True,
    ).stdout
    colors = json.loads(out)["colors"]
    role = lambda k: colors[k]["default"]["color"]
    t = {
        "BG": role("background"),
        "FG": role("on_background"),
        "BORDER": role("outline_variant"),
        "TRACK": role("surface_container"),
        "ACCENT": role("primary"),
        "ON_ACCENT": role("on_primary"),
        "WARM": role("tertiary"),
    }
    t["DARK"] = darken(t["BG"], 0.85)
    t.update(FIXED)
    return t


def w(path, content):
    Path(path).write_text(content)


